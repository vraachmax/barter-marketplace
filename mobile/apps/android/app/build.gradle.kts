// The Rust .so files are generated by ../scripts/build-rust.sh before assembling.
// Never silently ship a Kotlin-only fake if JNI libraries are missing.
tasks.register("verifyRustLibraries") {
    doLast {
        for (abi in listOf("arm64-v8a", "x86_64")) {
            val lib = file("src/main/jniLibs/$abi/libbarter_core.so")
            check(lib.isFile) { "Missing $lib. Run bash scripts/build-rust.sh in mobile/apps/android" }
        }
    }
}
tasks.matching { it.name == "preBuild" }.configureEach {
    dependsOn("verifyRustLibraries")
}
