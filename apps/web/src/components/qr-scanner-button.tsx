'use client';

import { useCallback, useEffect, useRef, useState } from 'react';
import { useRouter } from 'next/navigation';
import { Camera, ScanQrCode, Upload, X } from 'lucide-react';

const LISTING_ID = /^[a-zA-Z0-9][a-zA-Z0-9_-]{2,127}$/;

/** A scanned QR is data, never an arbitrary redirect or JavaScript URL. */
export function listingPathFromQr(raw: string, currentHost: string): string | null {
  const value = raw.trim();
  if (LISTING_ID.test(value)) return '/listing/' + encodeURIComponent(value);
  if (value.startsWith('/listing/')) {
    const id = value.slice('/listing/'.length).split(/[?#/]/, 1)[0];
    return LISTING_ID.test(id) ? '/listing/' + encodeURIComponent(id) : null;
  }
  try {
    const url = new URL(value);
    if (!['https:', 'http:'].includes(url.protocol)) return null;
    // QR codes generated by the live app must also work inside Vercel previews.
    if (url.hostname !== currentHost && url.hostname !== 'web-one-blond-66.vercel.app') return null;
    const match = /^\/listing\/([^/]+)\/?$/.exec(url.pathname);
    if (!match) return null;
    const id = decodeURIComponent(match[1]);
    return LISTING_ID.test(id) ? '/listing/' + encodeURIComponent(id) : null;
  } catch { return null; }
}

type QrReader = typeof import('jsqr')['default'];

export default function QrScannerButton({ onExchangeCode }: { onExchangeCode?: (code: string) => boolean }) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [error, setError] = useState('');
  const [manual, setManual] = useState('');
  const [cameraReady, setCameraReady] = useState(false);
  const dialog = useRef<HTMLDialogElement>(null);
  const video = useRef<HTMLVideoElement>(null);
  const canvas = useRef<HTMLCanvasElement>(null);

  const onCode = useCallback((raw: string): boolean => {
    if (onExchangeCode) {
      if (!onExchangeCode(raw.trim())) {
        setError('Это не QR-код подтверждения текущего обмена.');
        return false;
      }
      setError('');
      setOpen(false);
      return true;
    }
    const path = listingPathFromQr(raw, window.location.hostname);
    if (!path) {
      setError('QR-код не содержит ссылку на объявление Barter.');
      return false;
    }
    setError('');
    setOpen(false);
    router.push(path);
    return true;
  }, [router, onExchangeCode]);

  useEffect(() => {
    const el = dialog.current;
    if (!el) return;
    if (open && !el.open) el.showModal();
    else if (!open && el.open) el.close();
  }, [open]);

  useEffect(() => {
    if (!open) return;
    let stopped = false;
    let stream: MediaStream | null = null;
    let raf = 0;
    let lastFrame = 0;
    const start = async () => {
      try {
        if (!navigator.mediaDevices?.getUserMedia) throw Error('NO_CAMERA');
        const decoder: QrReader = (await import('jsqr')).default;
        if (stopped) return;
        stream = await navigator.mediaDevices.getUserMedia({
          audio: false, video: { facingMode: { ideal: 'environment' } },
        });
        if (stopped) { stream.getTracks().forEach(track => track.stop()); return; }
        const element = video.current;
        if (!element) return;
        element.srcObject = stream;
        await element.play();
        if (stopped) return;
        setCameraReady(true);
        const frame = (now: number) => {
          if (stopped) return;
          if (now - lastFrame > 150 && element.readyState >= 2) {
            lastFrame = now;
            const output = canvas.current;
            const ctx = output?.getContext('2d', { willReadFrequently: true });
            if (output && ctx && element.videoWidth > 0) {
              const width = Math.min(640, element.videoWidth);
              const height = Math.round(width * element.videoHeight / element.videoWidth);
              output.width = width; output.height = height;
              ctx.drawImage(element, 0, 0, width, height);
              const pixels = ctx.getImageData(0, 0, width, height);
              const result = decoder(pixels.data, width, height, { inversionAttempts: 'attemptBoth' });
              if (result && onCode(result.data)) return;
            }
          }
          raf = requestAnimationFrame(frame);
        };
        raf = requestAnimationFrame(frame);
      } catch {
        if (!stopped) setError('Не удалось включить камеру. Разрешите доступ или выберите снимок QR-кода.');
      }
    };
    void start();
    return () => {
      stopped = true;
      cancelAnimationFrame(raf);
      stream?.getTracks().forEach(track => track.stop());
      if (video.current) video.current.srcObject = null;
      setCameraReady(false);
    };
  }, [open, onCode]);

  async function onImage(file: File | undefined) {
    if (!file) return;
    const objectUrl = URL.createObjectURL(file);
    try {
      const decoder: QrReader = (await import('jsqr')).default;
      const image = new Image();
      image.src = objectUrl;
      await image.decode();
      const output = canvas.current;
      const context = output?.getContext('2d', { willReadFrequently: true });
      if (!output || !context) throw Error('NO_CANVAS');
      const scale = Math.min(1, 1400 / Math.max(image.naturalWidth, image.naturalHeight));
      output.width = Math.max(1, Math.round(image.naturalWidth * scale));
      output.height = Math.max(1, Math.round(image.naturalHeight * scale));
      context.drawImage(image, 0, 0, output.width, output.height);
      const data = context.getImageData(0, 0, output.width, output.height);
      const result = decoder(data.data, output.width, output.height, { inversionAttempts: 'attemptBoth' });
      if (!result) setError('Не удалось распознать QR-код на изображении.');
      else onCode(result.data);
    } catch {
      setError('Не удалось прочитать изображение. Попробуйте другое фото.');
    } finally {
      URL.revokeObjectURL(objectUrl);
    }
  }

  return (
    <>
      <button type="button" aria-label={onExchangeCode ? 'Сканировать QR подтверждения обмена' : 'Сканировать QR-код'} title={onExchangeCode ? 'Сканировать QR обмена' : 'Сканировать QR-код'}
        onClick={() => { setError(''); setManual(''); setOpen(true); }}
        className={onExchangeCode ? 'exchange-qr-trigger' : 'grid h-11 w-11 shrink-0 place-items-center rounded-[14px] bg-[var(--bg-surface)] text-foreground shadow-[0_3px_14px_rgba(24,24,48,.07)] focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#ff5a0a]'}>
        <ScanQrCode size={20} strokeWidth={2} aria-hidden />{onExchangeCode ? <span>Сканировать QR-код</span> : null}
      </button>
      <dialog ref={dialog} onCancel={() => setOpen(false)}
        aria-label="Сканер QR-кода Barter"
        className="fixed inset-0 m-auto w-[calc(100%-32px)] max-w-[440px] max-h-[calc(100dvh-48px)] overflow-y-auto rounded-[26px] border-0 bg-[var(--bg-page)] p-0 text-foreground shadow-2xl backdrop:bg-black/70">
        <div className="flex items-center justify-between gap-2 px-5 pt-5 pb-3">
          <div>
            <h2 className="text-[20px] font-bold">Сканировать QR-код</h2>
            <p className="mt-1 text-xs text-muted-foreground">{onExchangeCode ? 'Наведите камеру на QR другого участника обмена' : 'Откройте объявление Barter по QR-коду'}</p>
          </div>
          <button onClick={() => setOpen(false)} type="button" aria-label="Закрыть сканер"
            className="grid size-11 shrink-0 place-items-center rounded-full bg-[var(--bg-muted)]"><X size={20} aria-hidden /></button>
        </div>
        <div className="relative mx-5 aspect-square overflow-hidden rounded-[22px] bg-[#101115]">
          <video ref={video} autoPlay muted playsInline aria-label="Камера для сканирования QR-кода"
            className="h-full w-full object-cover" />
          <span className="pointer-events-none absolute inset-[14%] rounded-2xl border-2 border-white/75" />
          {!cameraReady ? (
            <div role="status" className="pointer-events-none absolute inset-0 grid place-items-center text-center text-sm text-white">
              <div className="flex flex-col items-center gap-2"><Camera size={26} aria-hidden />Ожидание камеры…</div>
            </div>
          ) : null}
        </div>
        <canvas ref={canvas} className="hidden" aria-hidden />
        {error ? <p role="alert" className="mx-5 mt-3 rounded-xl bg-[var(--bg-muted)] px-3 py-2 text-sm text-foreground">{error}</p> : null}
        <div className="space-y-3 p-5">
          <label className="flex min-h-11 cursor-pointer items-center justify-center gap-2 rounded-full bg-[var(--bg-muted)] text-sm font-semibold">
            <Upload size={17} aria-hidden /> Выбрать QR из фото
            <input type="file" accept="image/*" className="sr-only" aria-label="Выбрать фото QR-кода"
              onChange={event => { void onImage(event.currentTarget.files?.[0]); event.currentTarget.value = ''; }} />
          </label>
          <form onSubmit={event => { event.preventDefault(); onCode(manual); }} className="flex gap-2">
            <input value={manual} onChange={event => setManual(event.target.value)}
              aria-label={onExchangeCode ? "Код обмена" : "Ссылка на объявление"} placeholder={onExchangeCode ? "Код обмена BX1..." : "Ссылка или код объявления"}
              className="min-w-0 min-h-11 flex-1 rounded-xl bg-[var(--bg-muted)] px-3 text-sm outline-none focus:ring-2 focus:ring-[#ff5a0a]" />
            <button type="submit" className="min-h-11 shrink-0 rounded-xl bg-[#ff5a0a] px-4 text-sm font-semibold text-white">Открыть</button>
          </form>
        </div>
      </dialog>
    </>
  );
}
