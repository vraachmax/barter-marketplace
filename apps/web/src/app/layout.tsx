// Theme bootstrap sets browser chrome before paint; ModeThemeSync keeps it current.
export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 5,
  viewportFit: 'cover',
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="ru" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: THEME_BOOTSTRAP,
          }}
        />
        {/* Restore the catalog independently from the display theme. */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{var m=new URLSearchParams(location.search).get('mode');if(m===null){var c=document.cookie.split(';').map(function(x){return x.trim()}).find(function(x){return x.indexOf('barter_catalog_mode=')===0});m=c?c.split('=')[1]:'market'}if(m!=='barter'&&m!=='both')m='market';document.documentElement.setAttribute('data-mode',m);}catch(e){}})();`,
          }}
        />
      </head>
      <body
        className={`${inter.variable} antialiased`}
      >
        <ThemeSync />
        <ModeThemeSync />
        <AuthProvider>
          <PresenceProvider>
            <GlobalChatWidget />
            <SupportWidget />
            <AppViewport>{children}</AppViewport>
          </PresenceProvider>
        </AuthProvider>
      </body>
    </html>
  );
}
